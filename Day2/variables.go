package main
import "fmt"

func main() {
	var age int = 25 // Declering an integer variable
	var name string = "Shahriar" // Declering a string variable
	var isStudent bool = false // Declering a boolean variable
	fmt.Println("Name:", name)
	fmt.Println("Age:", age)
	fmt.Println("Is Student:", isStudent)

	// multiple variable declaration
	var a, b, c int = 1, 3, 5
	fmt.Println("a:", a, "b:", b, "c:", c)
}

